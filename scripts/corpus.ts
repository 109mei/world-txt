export type Outcome = 'read' | 'noise' | 'blocked' | 'redundant' | 'same';

export interface Tried {
  text: string;
  outcome: Outcome;
  reading: string | null;
  block: string | null;
  noise: string | null;
}

/** 意味なしになった文の原因の分け方 */
export type NoiseCause = '辞書にない言葉' | '結果を願う文' | '言い回しの規則の不足';

const WISH = /(増え|増す|減る|減っ|減ら|なくなる|無くなる|起きない|起こらない|尽きない|下がる|上がる|足りる|豊か|止まる|広がる|広まる|安くなる|高くなる|続く|守られ|進む|発展|進歩|解決)/u;

export function noiseCause(t: Tried): NoiseCause {
  if (t.noise?.startsWith('unknown-words')) return '辞書にない言葉';
  if (WISH.test(t.text)) return '結果を願う文';
  return '言い回しの規則の不足';
}

function classify(res: EditResult): Outcome {
  if (!res.block) return 'read';
  if (res.block === 'noise') return 'noise';
  if (res.block === 'redundant') return 'redundant';
  if (res.block === 'same') return 'same';
  return 'blocked';
}

/** 書いたらどうなるか（世界は変えない） */
export function tryWrite(g: GameState, target: { kind: 'new' } | { kind: 'law'; id: string }, text: string): Tried {
  const plan = planWrite(g, gameData, target, text);
  let res = plan.result;
  if (!plan.block && !res.understood) res = { ...res, block: 'noise' };
  return {
    text,
    outcome: classify(res),
    reading: res.reading,
    block: res.block,
    noise: res.noise ? `${res.noise.kind}${res.noise.words.length ? `:${res.noise.words.join('/')}` : ''}` : null,
  };
}

/** 通じた（意味なし以外）割合 */
export function understoodRate(list: readonly Tried[]): number {
  return list.length === 0 ? 1 : list.filter((t) => t.outcome !== 'noise').length / list.length;
}

export function runAdd(stage: StageId, free: boolean): Tried[] {
  const st = gameData.stageById.get(stage)!;
  return ADD[stage].map((text) => {
    const g = createGame(gameData, stage, 1, free ? null : accessFor(gameData, stage, st.unlock));
    return tryWrite(g, { kind: 'new' }, text);
  });
}

export function runRewrite(free: boolean): (Tried & { law: string })[] {
  const out: (Tried & { law: string })[] = [];
  for (const [law, texts] of Object.entries(REWRITE)) {
    for (const text of texts) {
      const g = createGame(gameData, 'food', 1, free ? null : accessFor(gameData, 'food', 0));
      out.push({ ...tryWrite(g, { kind: 'law', id: law }, text), law });
    }
  }
  return out;
}

const pct = (x: number) => `${Math.round(x * 100)}%`;

function main(): void {
  const quiet = process.argv.includes('--quiet');
  const counts = (list: readonly Tried[]) => {
    const c: Record<Outcome, number> = { read: 0, noise: 0, blocked: 0, redundant: 0, same: 0 };
    for (const t of list) c[t.outcome] += 1;
    return c;
  };
  console.log('== 書き足し（はじめて遊べる筆の位。通じる＝意味なし以外）');
  const allAdd: Tried[] = [];
  const noiseList: (Tried & { stage: string })[] = [];
  for (const stage of Object.keys(ADD) as StageId[]) {
    const list = runAdd(stage, false);
    allAdd.push(...list);
    const c = counts(list);
    console.log(`${stage.padEnd(8)} ${String(list.length).padStart(3)}文  通じる ${pct(understoodRate(list)).padStart(4)}  （読めた ${c.read}・止まる ${c.blocked}・重複 ${c.redundant}・同じ ${c.same}・意味なし ${c.noise}）`);
    for (const t of list) if (t.outcome === 'noise') noiseList.push({ ...t, stage });
  }
  console.log(`全体     ${String(allAdd.length).padStart(3)}文  通じる ${pct(understoodRate(allAdd))}`);
  const rw = runRewrite(true);
  const rc = counts(rw);
  console.log(`\n== 行の書き換え（筆の位の制限なし）${rw.length}文  通じる ${pct(understoodRate(rw))}（読めた ${rc.read}・同じ ${rc.same}・重複 ${rc.redundant}・止まる ${rc.blocked}・意味なし ${rc.noise}）`);
  const rw0 = runRewrite(false);
  console.log(`（食料危機・見習いの筆では 止まる ${rw0.filter((t) => t.outcome === 'blocked').length}文）`);
  if (quiet) return;
  const causes = new Map<NoiseCause, string[]>();
  for (const t of noiseList) {
    const k = noiseCause(t);
    causes.set(k, [...(causes.get(k) ?? []), `${t.stage}:${t.text}${t.noise ? `（${t.noise}）` : ''}`]);
  }
  for (const t of rw.filter((x) => x.outcome === 'noise')) {
    const k = noiseCause(t);
    causes.set(k, [...(causes.get(k) ?? []), `行 ${t.law}:${t.text}${t.noise ? `（${t.noise}）` : ''}`]);
  }
  console.log('\n== 意味なしになった文（原因ごと）');
  for (const [k, v] of causes) {
    console.log(`\n■ ${k} ${v.length}`);
    for (const s of v) console.log(`  ${s}`);
  }
}

